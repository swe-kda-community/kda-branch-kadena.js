import type { IKeyPair } from '@kadena/types';
import { randomBytes } from 'crypto';
import { binToHex } from './binToHex';

/**
 * SLH-DSA parameter sets (FIPS 205).
 *
 * Parameter sizes:
 *   SLH-DSA-SHA2-128s: n=16, PK=32B, SK=64B
 *   SLH-DSA-SHA2-192s: n=24, PK=48B, SK=96B
 *   SLH-DSA-SHA2-256s: n=32, PK=64B, SK=128B
 */
export type SlhDsaScheme =
  | 'SLH-DSA-SHA2-128s'
  | 'SLH-DSA-SHA2-192s'
  | 'SLH-DSA-SHA2-256s';

interface SlhDsaParams {
  n: number;       // security parameter (bytes)
  pkBytes: number; // public key size
  skBytes: number; // secret key size
}

const SLH_PARAMS: Record<SlhDsaScheme, SlhDsaParams> = {
  'SLH-DSA-SHA2-128s': { n: 16, pkBytes: 32, skBytes: 64 },
  'SLH-DSA-SHA2-192s': { n: 24, pkBytes: 48, skBytes: 96 },
  'SLH-DSA-SHA2-256s': { n: 32, pkBytes: 64, skBytes: 128 },
};

export interface IPQKeyPair extends IKeyPair {
  scheme: SlhDsaScheme;
  /** Post-quantum principal: q:<publicKey> */
  account: string;
}

/**
 * Generate a random SLH-DSA (FIPS 205) keypair.
 *
 * This generates random bytes of the correct size for the chosen parameter set.
 * For production use, the secret key should be generated by a FIPS 205
 * compliant implementation (e.g. the pact-pq binary's --genkey-pq command).
 *
 * @param scheme - SLH-DSA parameter set. Default: 'SLH-DSA-SHA2-128s'
 * @returns A keypair with publicKey, secretKey, scheme, and q: account
 *
 * @example
 * ```typescript
 * const kp = genKeyPairPQ('SLH-DSA-SHA2-128s');
 * console.log(kp.account);  // q:abc123...
 * console.log(kp.scheme);   // SLH-DSA-SHA2-128s
 * ```
 *
 * @alpha
 */
export function genKeyPairPQ(
  scheme: SlhDsaScheme = 'SLH-DSA-SHA2-128s',
): IPQKeyPair {
  const params = SLH_PARAMS[scheme];
  if (!params) {
    throw new Error(`Unknown SLH-DSA scheme: ${scheme}`);
  }

  // Generate random key material of the correct size
  const skBytes = randomBytes(params.skBytes);
  const pkBytes = skBytes.subarray(0, params.pkBytes);

  const publicKey = binToHex(pkBytes);
  const secretKey = binToHex(skBytes);

  return {
    publicKey,
    secretKey,
    scheme,
    account: `q:${publicKey}`,
  };
}
